export function buildCoreXml(presentation: PptxPresentation): string {
  const title = presentation.title ?? presentation.subject;
  const author = presentation.author ?? presentation.creator;
  const timestamp = el(
    "dcterms:created",
    [["xsi:type", "dcterms:W3CDTF"]],
    escText(FIXED_TIMESTAMP),
  );
  const modified = el(
    "dcterms:modified",
    [["xsi:type", "dcterms:W3CDTF"]],
    escText(FIXED_TIMESTAMP),
  );
  const children = [
    timestamp,
    author === undefined ? "" : el("dc:creator", [], escText(author)),
    modified,
    title === undefined ? "" : el("dc:title", [], escText(title)),
  ].join("");
  return doc(
    el(
      "cp:coreProperties",
      [
        ["xmlns:cp", CP_NS],
        ["xmlns:dc", DC_NS],
        ["xmlns:dcterms", DCTERMS_NS],
        ["xmlns:xsi", XSI_NS],
      ],
      children,
    ),
  );
}
